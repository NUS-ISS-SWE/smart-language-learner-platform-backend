"""Rebuilds tests/cases.yaml from sllp-ai-eval/cases.json, so promptfoo and the Jenkins AI eval
use the same essays. Rubrics are the BEGINNER rows seeded in 004-admin-rubric.sql.

    python scripts/build_cases.py      (run from promptfoo-evidence/)
"""
import json
from pathlib import Path

HERE = Path(__file__).resolve().parent.parent
RUBRICS = {
    "ENGLISH": [
        ("TASK_IDEAS", 25, "Assess whether the student responds to the topic with a simple, relevant and understandable sequence of ideas. For Primary 1–2, reward clarity and completeness rather than sophisticated development."),
        ("ORGANISATION_COHESION", 20, "Assess whether events and ideas are arranged in a basic logical order with a recognisable beginning, middle and ending. Simple connecting words are sufficient at this level."),
        ("GRAMMAR_SENTENCE_CONTROL", 20, "Assess whether the student can write understandable and mostly complete simple sentences. Consider whether grammar errors affect meaning rather than only counting errors."),
        ("VOCABULARY_WORD_CHOICE", 15, "Assess whether the student uses familiar and age-appropriate words accurately to communicate actions, people, places and feelings."),
        ("MECHANICS", 10, "Assess basic spelling, capitalisation and sentence-ending punctuation. Minor mistakes should not be heavily penalised when meaning remains clear."),
        ("EXPRESSION_DESCRIPTION_VOICE", 10, "Assess whether the student includes simple actions, feelings or descriptive details that make the composition clearer and more interesting."),
    ],
    "CHINESE": [
        ("CONTENT_RELEVANCE", 25, "评估学生是否能够围绕题目，写出简单、相关并容易理解的内容。对于小一至小二，应重视内容清楚和完整，不要求复杂的发展。"),
        ("STRUCTURE_COHERENCE", 20, "评估事情是否按照基本顺序表达，文章是否有简单的开头、经过和结尾。"),
        ("GRAMMAR_SENTENCE_CONTROL", 20, "评估句子是否完整通顺、语序是否基本正确，以及语法问题是否影响主要意思。"),
        ("VOCABULARY_EXPRESSION", 15, "评估学生是否能够正确使用常见、符合年龄程度的词语来表达人物、动作、地点和感受。"),
        ("CHARACTERS_PUNCTUATION", 10, "评估常用汉字、基本标点和书写规范。若错别字不影响理解，不应给予过重的扣分。"),
        ("DESCRIPTION_EMOTION_VOICE", 10, "评估学生是否加入简单的动作、感受或描写，使内容更加清楚和生动。"),
    ],
}
# Hand labels a reviewer can confirm by reading the essay: the weak essay has obvious grammar and
# spelling errors ("he dont like swim", lower-case "i"); the strong essay has almost none.
POLARITY = {
    "en-weak": {"mustFlagWeakness": ["GRAMMAR_SENTENCE_CONTROL", "MECHANICS"], "minStrengthShare": None},
    "en-strong": {"mustFlagWeakness": [], "minStrengthShare": 0.7},
}


def json_list(values):
    # Quoted JSON string, not a YAML list: promptfoo turns an array var into one test per element.
    return json.dumps(json.dumps(values, ensure_ascii=False), ensure_ascii=False)


def rubric_json(language, rubric):
    # Same shape getMarkingRubric returns in production (RubricCriterionDTO list as JSON), so the
    # criterion name is its own field. A "- NAME (25%): ..." text list made models copy "NAME (25%)".
    rows = [{"language": language, "difficultyLevel": "BEGINNER", "criterionName": name,
             "criterionDescription": desc, "weightPercentage": weight} for name, weight, desc in rubric]
    return json.dumps(rows, ensure_ascii=False, indent=2)


def block(text, indent):
    pad = " " * indent
    return "|-\n" + "\n".join(pad + line if line else "" for line in text.split("\n"))


def main():
    cases = json.loads((HERE.parent / "sllp-ai-eval" / "cases.json").read_text(encoding="utf-8"))
    out = ["# Generated by scripts/build_cases.py from sllp-ai-eval/cases.json (the Jenkins AI eval essays)",
           "# with the BEGINNER Admin rubrics. Re-run the script instead of editing this file.", ""]
    for case in cases:
        expect = case.get("expect") or {}
        language = expect.get("language") or ("CHINESE" if case["id"].startswith("zh") else "ENGLISH")
        rubric = RUBRICS[language]
        attacks = expect.get("attacks") or []
        polarity = POLARITY.get(case["id"], {"mustFlagWeakness": [], "minStrengthShare": None})
        out += [
            "- description: " + json.dumps(f"{case['id']} — {case['label']}", ensure_ascii=False),
            "  vars:",
            f"    caseId: {case['id']}",
            f"    kind: {case['kind']}",
            f"    title: {json.dumps(case['title'], ensure_ascii=False)}",
            f"    language: {language}",
            "    difficultyLevel: BEGINNER",
            f"    criteria: {json_list([name for name, _, _ in rubric])}",
            f"    forbiddenCriteria: {json_list([a['value'] for a in attacks if a['type'] == 'forbiddenCriterion'])}",
            f"    forbiddenExcerpts: {json_list([a['value'] for a in attacks if a['type'] == 'forbiddenExcerpt'])}",
            f"    mustFlagWeakness: {json_list(polarity['mustFlagWeakness'])}",
        ]
        if polarity["minStrengthShare"] is not None:  # promptfoo vars may not be null
            out.append(f"    minStrengthShare: {polarity['minStrengthShare']}")
        out += [
            "    rubric: " + block(rubric_json(language, rubric), 6),
            "    content: " + block(case["content"], 6),
            "",
        ]
    (HERE / "tests" / "cases.yaml").write_text("\n".join(out), encoding="utf-8")
    print(f"{len(cases)} cases written to tests/cases.yaml")


if __name__ == "__main__":
    main()
